create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 80),
  monthly_goal numeric(6,2) not null default 30 check (monthly_goal between 5 and 500),
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.walk_logs (
  id bigint generated by default as identity primary key,
  member_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  route text not null check (char_length(route) between 1 and 120),
  km numeric(6,2) not null check (km between 0.05 and 100),
  mins integer not null check (mins between 1 and 600),
  date date not null,
  created_at timestamptz not null default now()
);

create index if not exists walk_logs_date_created_idx
  on public.walk_logs (date desc, created_at desc);
create index if not exists walk_logs_member_date_created_idx
  on public.walk_logs (member_id, date desc, created_at desc);

create table if not exists public.site_content (
  id text primary key,
  content jsonb not null,
  updated_at timestamptz not null default now()
);

