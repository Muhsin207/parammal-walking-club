alter table public.profiles enable row level security;
alter table public.walk_logs enable row level security;
alter table public.site_content enable row level security;

grant usage on schema public to anon, authenticated;

grant select on public.profiles to authenticated;
grant insert on public.profiles to authenticated;
grant update (monthly_goal) on public.profiles to authenticated;

grant select on public.walk_logs to authenticated;
grant insert on public.walk_logs to authenticated;
grant select on public.site_content to anon, authenticated;
grant insert, update, delete on public.site_content to authenticated;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
  for select using (auth.uid() = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles
  for insert with check (auth.uid() = id and is_admin = false);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name, monthly_goal, is_admin)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data->>'display_name'), ''), 'Member'), 80),
    30,
    false
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

insert into public.profiles (id, display_name, monthly_goal, is_admin)
select
  users.id,
  left(coalesce(nullif(trim(users.raw_user_meta_data->>'display_name'), ''), 'Member'), 80),
  30,
  false
from auth.users users
on conflict (id) do nothing;

drop policy if exists "profiles_update_own_goal" on public.profiles;
create policy "profiles_update_own_goal" on public.profiles
  for update using (auth.uid() = id)
  with check (auth.uid() = id);

create or replace function public.enforce_profile_updates()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.display_name is distinct from old.display_name
     or new.is_admin is distinct from old.is_admin
     or new.created_at is distinct from old.created_at then
    raise exception 'Only monthly_goal may be updated';
  end if;
  return new;
end;
$$;

drop trigger if exists enforce_profile_updates on public.profiles;
create trigger enforce_profile_updates
  before update on public.profiles
  for each row execute function public.enforce_profile_updates();

drop policy if exists "walk_logs_public_read" on public.walk_logs;
drop policy if exists "walk_logs_select_own" on public.walk_logs;
create policy "walk_logs_select_own" on public.walk_logs
  for select using (auth.uid() = member_id);

drop policy if exists "walk_logs_insert_own" on public.walk_logs;
create policy "walk_logs_insert_own" on public.walk_logs
  for insert with check (
    auth.uid() = member_id
    and name = (select display_name from public.profiles where id = auth.uid())
  );

drop policy if exists "site_content_public_read" on public.site_content;
create policy "site_content_public_read" on public.site_content
  for select using (id = 'main');

drop policy if exists "site_content_admin_write" on public.site_content;
create policy "site_content_admin_write" on public.site_content
  for all using (
    id = 'main'
    and exists (select 1 from public.profiles where id = auth.uid() and is_admin = true)
  )
  with check (
    id = 'main'
    and exists (select 1 from public.profiles where id = auth.uid() and is_admin = true)
  );
